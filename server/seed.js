function ean13(id) {
  const body = '462711' + String((id * 7919) % 1000000).padStart(6, '0');
  let sum = 0;
  for (let i = 0; i < 12; i++) sum += Number(body[i]) * (i % 2 === 0 ? 1 : 3);
  return body + ((10 - (sum % 10)) % 10);
}

