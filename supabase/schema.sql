-- Функции (RPC). Запись игры и участника вместе со связями — одна транзакция.

create or replace function public.me() returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('id', id, 'username', username, 'name', name, 'role', role)
  from public.profiles where auth_id = auth.uid()
$$;

-- Игра вместе с авторами и жанрами (многие ко многим). security invoker:
-- действуют политики RLS, участник получит отказ 42501.
create or replace function public.save_game(p jsonb) returns bigint
language plpgsql set search_path = public as $$
declare gid bigint := nullif(p ->> 'id', '')::bigint;
begin
  if gid is null or gid = 0 then
    insert into games (title, barcode, year, play_time_min, min_players, max_players,
                       publisher_id, copies_total, copies_available)
    values (p ->> 'title', p ->> 'barcode', (p ->> 'year')::int, (p ->> 'playTimeMin')::int,
            (p ->> 'minPlayers')::int, (p ->> 'maxPlayers')::int, (p ->> 'publisherId')::bigint,
            (p ->> 'copiesTotal')::int, (p ->> 'copiesAvailable')::int)
    returning id into gid;
  else
    update games set title = p ->> 'title', barcode = p ->> 'barcode',
      year = (p ->> 'year')::int, play_time_min = (p ->> 'playTimeMin')::int,
      min_players = (p ->> 'minPlayers')::int, max_players = (p ->> 'maxPlayers')::int,
      publisher_id = (p ->> 'publisherId')::bigint, copies_total = (p ->> 'copiesTotal')::int,
      copies_available = (p ->> 'copiesAvailable')::int
    where id = gid;
    if not found then
      raise exception 'Игра не найдена или нет прав на изменение' using errcode = '42501';
    end if;
    delete from game_designers where game_id = gid;
    delete from game_genres where game_id = gid;
  end if;
  insert into game_designers (game_id, designer_id)
    select gid, value::bigint from jsonb_array_elements_text(p -> 'designerIds');
  insert into game_genres (game_id, genre_id)
    select gid, value::bigint from jsonb_array_elements_text(p -> 'genreIds');
  return gid;
end $$;

-- Участник вместе с клубной картой (один к одному).
create or replace function public.save_member(p jsonb) returns bigint
language plpgsql set search_path = public as $$
declare mid bigint := nullif(p ->> 'id', '')::bigint;
begin
  if mid is null or mid = 0 then
    insert into members (last_name, first_name, email, phone, city)
    values (p ->> 'lastName', p ->> 'firstName', p ->> 'email', p ->> 'phone', p ->> 'city')
    returning id into mid;
  else
    update members set last_name = p ->> 'lastName', first_name = p ->> 'firstName',
      email = p ->> 'email', phone = p ->> 'phone', city = p ->> 'city'
    where id = mid;
    if not found then
      raise exception 'Участник не найден или нет прав на изменение' using errcode = '42501';
    end if;
  end if;
  insert into member_cards (member_id, number, issued_year, max_games)
  values (mid, upper(p -> 'card' ->> 'number'), (p -> 'card' ->> 'issuedYear')::int,
          (p -> 'card' ->> 'maxGames')::int)
  on conflict (member_id) do update set number = excluded.number,
    issued_year = excluded.issued_year, max_games = excluded.max_games;
  return mid;
end $$;

-- Быстрая выдача/возврат коробки из карточки игры (сотрудник).
create or replace function public.game_checkout(p_id bigint) returns void
language plpgsql set search_path = public as $$
begin
  if not public.is_role('staff') then
    raise exception 'Недостаточно прав для этого действия' using errcode = '42501';
  end if;
  update games set copies_available = copies_available - 1
  where id = p_id and copies_available > 0 and deleted_at is null;
  if not found then
    raise exception 'Свободных коробок нет' using errcode = 'PT409';
  end if;
end $$;

create or replace function public.game_return(p_id bigint) returns void
language plpgsql set search_path = public as $$
begin
  if not public.is_role('staff') then
    raise exception 'Недостаточно прав для этого действия' using errcode = '42501';
  end if;
  update games set copies_available = copies_available + 1
  where id = p_id and copies_available < copies_total;
  if not found then
    raise exception 'Все коробки уже в клубе' using errcode = 'PT409';
  end if;
end $$;

-- Выдачи. security definer + явная проверка роли: таблица loans закрыта для записи.
create or replace function public.issue_loan(p_game bigint, p_user bigint) returns bigint
language plpgsql security definer set search_path = public as $$
declare lid bigint;
begin
  if not public.is_role('staff') then
    raise exception 'Недостаточно прав для этого действия' using errcode = '42501';
  end if;
  if not exists (select 1 from profiles where id = p_user and role = 'member') then
    raise exception 'Выдавать игры можно только участникам клуба' using errcode = 'PT409';
  end if;
  if (select count(*) from loans where user_id = p_user and returned_at is null) >= 3 then
    raise exception 'У участника уже 3 игры на руках' using errcode = 'PT409';
  end if;
  update games set copies_available = copies_available - 1
  where id = p_game and copies_available > 0 and deleted_at is null;
  if not found then
    raise exception 'Свободных коробок нет' using errcode = 'PT409';
  end if;
  insert into loans (game_id, user_id, due_date)
  values (p_game, p_user, now() + interval '14 days') returning id into lid;
  return lid;
end $$;

create or replace function public.close_loan(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare gid bigint;
begin
  if not public.is_role('staff') then
    raise exception 'Недостаточно прав для этого действия' using errcode = '42501';
  end if;
  update loans set returned_at = now() where id = p_id and returned_at is null
  returning game_id into gid;
  if gid is null then
    raise exception 'Выдача уже закрыта' using errcode = 'PT409';
  end if;
  update games set copies_available = least(copies_available + 1, copies_total) where id = gid;
end $$;

-- Продление — только своей выдачи, не больше двух раз и не после срока.
create or replace function public.extend_loan(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare l loans;
begin
  select * into l from loans where id = p_id;
  if l.id is null or l.user_id is distinct from public.my_profile_id() then
    raise exception 'Можно продлить только свою выдачу' using errcode = '42501';
  end if;
  if l.returned_at is not null then
    raise exception 'Игра уже возвращена' using errcode = 'PT409';
  end if;
  if l.due_date < now() then
    raise exception 'Срок истёк — продлить нельзя, верните игру' using errcode = 'PT409';
  end if;
  if l.extensions >= 2 then
    raise exception 'Продлевать можно не больше двух раз' using errcode = 'PT409';
  end if;
  update loans set due_date = due_date + interval '7 days', extensions = extensions + 1
  where id = p_id;
end $$;

create or replace function public.club_stats() returns json
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_role('admin') then
    raise exception 'Недостаточно прав для этого действия' using errcode = '42501';
  end if;
  return json_build_object(
    'games', (select count(*) from games where deleted_at is null),
    'copiesTotal', (select coalesce(sum(copies_total), 0) from games where deleted_at is null),
    'copiesAvailable', (select coalesce(sum(copies_available), 0) from games where deleted_at is null),
    'designers', (select count(*) from designers where deleted_at is null),
    'genres', (select count(*) from genres where deleted_at is null),
    'publishers', (select count(*) from publishers where deleted_at is null),
    'members', (select count(*) from members where deleted_at is null),
    'users', (select count(*) from profiles),
    'usersByRole', (select coalesce(json_object_agg(role, n), '{}'::json)
                    from (select role, count(*) as n from profiles group by role) r),
    'activeLoans', (select count(*) from loans where returned_at is null),
    'overdueLoans', (select count(*) from loans where returned_at is null and due_date < now()),
    'deletedRecords', (select (select count(*) from games where deleted_at is not null)
                            + (select count(*) from designers where deleted_at is not null)
                            + (select count(*) from members where deleted_at is not null))
  );
end $$;

