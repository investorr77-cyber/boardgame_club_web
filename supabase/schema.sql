-- Клуб настольных игр — схема базы данных Supabase (PostgreSQL).
-- Выполняется один раз в SQL Editor проекта. Повторный запуск пересоздаёт схему.
--
-- Сущности (8): profiles, publishers, genres, designers, games, members,
-- member_cards, loans. Связующие таблицы: game_designers, game_genres.
-- Связи:
--   один к одному    members — member_cards (карта не существует без участника);
--   один ко многим   publishers → games, games → loans, profiles → loans;
--   многие ко многим games ↔ designers, games ↔ genres.
-- Права проверяет сама база (Row Level Security): клиент только скрывает кнопки.

drop table if exists public.loans, public.member_cards, public.members,
  public.game_genres, public.game_designers, public.games, public.designers,
  public.genres, public.publishers, public.profiles cascade;
drop type if exists public.app_role cascade;

create type public.app_role as enum ('member', 'staff', 'admin');

-- Пользователи приложения. Учётная запись — в auth.users (Supabase Auth),
-- здесь профиль и роль. Профиль создаётся триггером при регистрации.
create table public.profiles (
  id bigint generated always as identity primary key,
  auth_id uuid not null unique references auth.users (id) on delete cascade,
  username text not null unique check (username ~ '^[A-Za-z0-9_]{3,20}$'),
  name text not null check (char_length(name) between 2 and 60),
  role public.app_role not null default 'member',
  created_at timestamptz not null default now()
);

create table public.publishers (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 2 and 80),
  country text not null check (char_length(btrim(country)) >= 2),
  founded_year int not null check (founded_year between 1800 and 2100),
  email text not null default '',
  deleted_at timestamptz
);

create table public.genres (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 2 and 40),
  description text not null default '',
  deleted_at timestamptz
);

create table public.designers (
  id bigint generated by default as identity primary key,
  last_name text not null check (char_length(btrim(last_name)) >= 2),
  first_name text not null check (char_length(btrim(first_name)) >= 2),
  country text not null,
  birth_year int not null check (birth_year between 1900 and 2100),
  deleted_at timestamptz
);

create table public.games (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 2 and 120),
  barcode text not null unique check (barcode ~ '^[0-9]{13}$'),
  year int not null check (year between 1900 and 2100),
  play_time_min int not null check (play_time_min between 1 and 1440),
  min_players int not null check (min_players >= 1),
  max_players int not null check (max_players >= min_players),
  publisher_id bigint not null references public.publishers (id) on delete restrict,
  copies_total int not null check (copies_total >= 0),
  copies_available int not null check (copies_available between 0 and copies_total),
  deleted_at timestamptz
);
create index games_publisher_idx on public.games (publisher_id);

create table public.game_designers (
  game_id bigint not null references public.games (id) on delete cascade,
  designer_id bigint not null references public.designers (id) on delete cascade,
  primary key (game_id, designer_id)
);

create table public.game_genres (
  game_id bigint not null references public.games (id) on delete cascade,
  genre_id bigint not null references public.genres (id) on delete cascade,
  primary key (game_id, genre_id)
);

create table public.members (
  id bigint generated by default as identity primary key,
  last_name text not null check (char_length(btrim(last_name)) >= 2),
  first_name text not null check (char_length(btrim(first_name)) >= 2),
  email text not null unique,
  phone text not null,
  city text not null,
  deleted_at timestamptz
);

-- Один к одному: первичный ключ карты — он же ссылка на участника.
create table public.member_cards (
  member_id bigint primary key references public.members (id) on delete cascade,
  number text not null unique,
  issued_year int not null check (issued_year between 1990 and 2100),
  max_games int not null check (max_games between 1 and 10)
);

create table public.loans (
  id bigint generated always as identity primary key,
  game_id bigint not null references public.games (id) on delete restrict,
  user_id bigint not null references public.profiles (id) on delete restrict,
  issued_at timestamptz not null default now(),
  due_date timestamptz not null,
  returned_at timestamptz,
  extensions int not null default 0 check (extensions between 0 and 2)
);
create index loans_user_idx on public.loans (user_id);
create index loans_game_idx on public.loans (game_id);

-- ---------------------------------------------------------------------------
-- Роль и профиль текущего пользователя. security definer: функции читают
-- profiles в обход RLS, иначе политика profiles ссылалась бы сама на себя.

create or replace function public.my_role() returns public.app_role
language sql stable security definer set search_path = public as $$
  select role from public.profiles where auth_id = auth.uid()
$$;

create or replace function public.my_profile_id() returns bigint
language sql stable security definer set search_path = public as $$
  select id from public.profiles where auth_id = auth.uid()
$$;

create or replace function public.is_role(variadic roles public.app_role[])
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() = any (roles), false)
$$;

-- Профиль при регистрации: логин и имя приходят в user_metadata, роль всегда
-- member — повысить её может только администратор.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (auth_id, username, name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1))
  );
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Row Level Security. Таблица прав совпадает с lib/models/permissions.dart:
--   каталог читают все вошедшие; правит сотрудник; физически удаляет
--   и восстанавливает администратор; участников видят сотрудник и администратор;
--   выдачи — свои участнику, все — сотруднику и администратору.

alter table public.profiles enable row level security;
alter table public.publishers enable row level security;
alter table public.genres enable row level security;
alter table public.designers enable row level security;
alter table public.games enable row level security;
alter table public.game_designers enable row level security;
alter table public.game_genres enable row level security;
alter table public.members enable row level security;
alter table public.member_cards enable row level security;
alter table public.loans enable row level security;

-- Гость (anon) не получает ничего: всё приложение доступно только после входа.
revoke all on all tables in schema public from anon;
grant select, insert, update, delete on all tables in schema public to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy profiles_select on public.profiles for select to authenticated
  using (auth_id = auth.uid() or public.is_role('staff', 'admin'));
create policy profiles_update on public.profiles for update to authenticated
  using (public.is_role('admin')) with check (public.is_role('admin'));

do $$
declare t text;
begin
  foreach t in array array['publishers', 'genres', 'designers', 'games',
                           'game_designers', 'game_genres'] loop
    execute format('create policy %1$s_select on public.%1$s for select to authenticated using (true)', t);
    execute format('create policy %1$s_insert on public.%1$s for insert to authenticated with check (public.is_role(''staff''))', t);
    execute format('create policy %1$s_update on public.%1$s for update to authenticated using (public.is_role(''staff'', ''admin'')) with check (public.is_role(''staff'', ''admin''))', t);
    execute format('create policy %1$s_delete on public.%1$s for delete to authenticated using (public.is_role(''admin'') or (%2$s and public.is_role(''staff'')))',
                   t, case when t like 'game\_%' then 'true' else 'false' end);
  end loop;
  foreach t in array array['members', 'member_cards'] loop
    execute format('create policy %1$s_select on public.%1$s for select to authenticated using (public.is_role(''staff'', ''admin''))', t);
    execute format('create policy %1$s_insert on public.%1$s for insert to authenticated with check (public.is_role(''staff''))', t);
    execute format('create policy %1$s_update on public.%1$s for update to authenticated using (public.is_role(''staff'', ''admin'')) with check (public.is_role(''staff'', ''admin''))', t);
    execute format('create policy %1$s_delete on public.%1$s for delete to authenticated using (public.is_role(''admin''))', t);
  end loop;
end $$;

-- Выдачи меняются только функциями ниже: напрямую в таблицу писать нельзя.
create policy loans_select on public.loans for select to authenticated
  using (user_id = public.my_profile_id() or public.is_role('staff', 'admin'));

