/// Штрихкод EAN-13: 12 цифр и контрольная цифра.
String ean13(int id) {
  final body = '462711${(id * 7919 % 1000000).toString().padLeft(6, '0')}';
  var sum = 0;
  for (var i = 0; i < 12; i++) {
    final digit = body.codeUnitAt(i) - 48;
    sum += i.isEven ? digit : digit * 3;
  }
  return '$body${(10 - sum % 10) % 10}';
}
